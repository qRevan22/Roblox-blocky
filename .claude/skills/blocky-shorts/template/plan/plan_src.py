"""Plan source for a vertical blocky Short: shots, accents and tags anchored to WORDS of the voice-over, not to seconds.
Re-run after every VO change; the times move with the words. Writes src/plan.gen.ts (and prints a short report).

    python plan/plan_src.py vo/timings.json

timings.json: {"turns": [{"turn": 1, "words": [{"w": "Hello", "t": 0.12, "end": 0.48}, ...]}, ...]}
"""
import json, sys
from pathlib import Path

FPS = 30
LEAD = 2  # captions appear 2 frames before the word

# ---- the story, by words ---------------------------------------------------------------------------------------
# A shot starts on its anchor word (turn, word, occurrence). Keep 4-7 s per shot on a Short, a cut only where the
# picture needs to change (a new subject, a reaction, the payoff). Each shot names its act mood.
SHOTS = [
    # id,     anchor (turn, word, nth), mood,   lens note
    ("S01", (1, "first", 1), "day", "medium, hero 3/4, face at ~38% of the height"),
    ("S02", (1, "then", 1), "dusk", "wide establishing, the key object in frame"),
    ("S03", (2, "finally", 1), "golden", "close-up payoff"),
]
# ONE accent word per sentence or moment, never more (yellow; everything else white).
ACCENT = {(1, "first"), (2, "finally")}
# Painted tags: only the story's key facts, on the key object, about one per 15 s. Never on everything.
TAGS = [
    # (turn, word, text, on-object note)
    (1, "first", "OPEN", "painted on the key object"),
]
CHUNK_WORDS = 2  # 1-2 lowercase words per caption chunk


def load(p):
    words = []
    for tr in json.loads(Path(p).read_text(encoding="utf8"))["turns"]:
        for w in tr["words"]:
            words.append({"turn": tr["turn"], "w": w["w"], "t": w["t"], "end": w["end"]})
    return words


def find(words, turn, word, nth=1):
    k = 0
    for w in words:
        if w["turn"] == turn and w["w"].lower().strip(".,!?;:\"'") == word.lower():
            k += 1
            if k == nth:
                return w
    raise SystemExit(f"anchor not found: turn {turn} word {word!r} #{nth}")


def main(p):
    words = load(p)
    total = words[-1]["end"] + 0.6
    shots = []
    for i, (sid, (tn, wd, nth), mood, note) in enumerate(SHOTS):
        t0 = 0.0 if i == 0 else find(words, tn, wd, nth)["t"]
        shots.append({"id": sid, "t": round(t0, 3), "mood": mood, "note": note})
    for a, b in zip(shots, shots[1:] + [{"t": total}]):
        a["end"] = round(b["t"], 3)
        if a["end"] - a["t"] < 1.5:
            print(f"WARN {a['id']} is only {a['end'] - a['t']:.2f} s")
    caps, chunk = [], []
    for w in words:
        chunk.append(w)
        if len(chunk) == CHUNK_WORDS or w["w"][-1:] in ".,!?;:":
            caps.append(chunk)
            chunk = []
    if chunk:
        caps.append(chunk)
    captions = [{
        "text": " ".join(c["w"].lower() for c in ch),
        "accent": [c["w"].lower() for c in ch if (c["turn"], c["w"].lower().strip(".,!?;:")) in ACCENT],
        "frame": max(0, round(ch[0]["t"] * FPS) - LEAD),
    } for ch in caps]
    tags = [{"text": tx, "t": round(find(words, tn, wd)["t"], 3), "note": nt} for tn, wd, tx, nt in TAGS]
    n_acc = sum(1 for c in captions if c["accent"])
    print(f"{len(shots)} shots, {len(captions)} caption chunks, {n_acc} accented, {len(tags)} tags, {total:.2f} s")
    if n_acc > max(1, total / 4):
        print("WARN too many accents: about one per sentence")
    if len(tags) > max(1, total / 15 + 1):
        print("WARN too many tags: about one per 15 s, key facts only")
    out = Path(__file__).resolve().parent.parent / "src" / "plan.gen.ts"
    out.write_text(
        "// generated by plan/plan_src.py; do not edit\n"
        f"export const FPS = {FPS};\nexport const DURATION = {round(total * FPS)};\n"
        f"export const SHOTS = {json.dumps(shots)} as const;\n"
        f"export const CAPTIONS = {json.dumps(captions)} as const;\n"
        f"export const TAGS = {json.dumps(tags)} as const;\n", encoding="utf8")
    print("wrote", out.name)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "vo/timings.json")
